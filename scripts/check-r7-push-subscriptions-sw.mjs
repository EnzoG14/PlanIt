  // Wait for Service Worker registration and activation
  const swInfo = await page.evaluate(async () => {
    const reg = await navigator.serviceWorker.ready
    // Wait until controller is claimed
    if (!navigator.serviceWorker.controller) {
      await new Promise(resolve => {
        navigator.serviceWorker.addEventListener('controllerchange', resolve, { once: true })
        setTimeout(resolve, 2000)
      })
    }
    const cacheNames = await caches.keys()
    const cachedUrls = []
    for (const name of cacheNames) {
      const cache = await caches.open(name)
      const keys = await cache.keys()
      cachedUrls.push(...keys.map(k => k.url))
    }
    return {
      scriptURL: reg.active?.scriptURL ?? null,
      state: reg.active?.state ?? null,
      hasController: Boolean(navigator.serviceWorker.controller),
      cacheNames,
      cachedCount: cachedUrls.length,
      hasSupabaseCache: cachedUrls.some(u => /supabase\.co/i.test(u)),
    }
  })

  assert.equal(swInfo.scriptURL, `${origin}/sw.js`)
  assert.equal(swInfo.state, 'activated')
  assert.equal(swInfo.hasController, true)
  assert.ok(swInfo.cacheNames.some(n => n.includes('workbox-precache')), 'Workbox precache must be created')
  assert.ok(swInfo.cachedCount >= 20, 'Workbox precache must populate static build assets')
  assert.equal(swInfo.hasSupabaseCache, false, 'Cache Storage must never contain supabase.co responses')
  record('Active Service Worker (/sw.js) registers, claims client, populates Workbox precache, and stores zero supabase.co entries', {
    cachedCount: swInfo.cachedCount,
    cacheNames: swInfo.cacheNames,
  })

  // 2. Verify offline navigation fallback to index.html (app shell works offline)
  await context.setOffline(true)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.locator('.auth-form').waitFor({ timeout: 10000 })
  await context.setOffline(false)
  record('Offline reload serves precached app shell (NavigationRoute -> index.html) without network')

  // 3. Test Service Worker push, notificationclick, and PLANIT_CLEAR_NOTIFICATIONS handlers directly inside the ServiceWorker Worker context
  let swWorker = context.serviceWorkers()[0]
  if (!swWorker) {
    swWorker = await context.waitForEvent('serviceworker', { timeout: 5000 })
  }
  assert.ok(swWorker, 'ServiceWorker target must be accessible in browser context')

  const swBehavior = await swWorker.evaluate(async () => {
    const shown = []
    const closedTags = []
    const activeNotifications = []

    const origShow = self.registration.showNotification.bind(self.registration)
    const origGet = self.registration.getNotifications.bind(self.registration)

    self.registration.showNotification = async (title, options) => {
      shown.push({ title, options })
      activeNotifications.push({
        tag: options.tag,
        data: options.data,
        close() {
          closedTags.push(options.tag)
        },
      })
    }
    self.registration.getNotifications = async () => [...activeNotifications]

    try {
      const dispatchPush = async payload => {
        let promise = Promise.resolve()
        const evt = new Event('push')
        evt.data =
          payload === null
            ? null
            : {
                text: () => (typeof payload === 'string' ? payload : JSON.stringify(payload)),
                json: () => (typeof payload === 'string' ? JSON.parse(payload) : payload),
              }
        evt.waitUntil = p => {
          promise = Promise.resolve(p)
        }
        self.dispatchEvent(evt)
        await promise
      }

      // Case A: Valid PushWireV1 with preview enabled
      const notifId = '44444444-4444-4444-8444-444444444444'
      const recipientId = '11111111-1111-4111-8111-111111111111'
      const eventId = '33333333-3333-4333-8333-333333333333'
      await dispatchPush({
        version: 1,
        notification_id: notifId,
        recipient_id: recipientId,
        title: '<b>Asado en el parque</b> https://evil.example/phish',
        body: 'Nos vemos a las 13hs <script>alert(1)</script> ' + 'x'.repeat(160),
        target: `/events/${eventId}/chat`,
      })

      // Case B: Malformed / external target / invalid payload falls back to generic notice and /notifications
      await dispatchPush({
        version: 1,
        notification_id: 'not-a-uuid',
        recipient_id: 'not-a-uuid',
        title: '',
        body: '',
        target: 'https://evil.example/steal',
      })

      // Case C: Non-JSON raw text payload falls back to generic notice
      await dispatchPush('<<<non-json-payload>>>')

      // Case D: PLANIT_CLEAR_NOTIFICATIONS message closes matching notifications
      let clearPromise = Promise.resolve()
      const msgEvt = new Event('message')
      msgEvt.data = {
        type: 'PLANIT_CLEAR_NOTIFICATIONS',
        recipient_id: recipientId,
        notification_ids: [notifId],
      }
      msgEvt.waitUntil = p => {
        clearPromise = Promise.resolve(p)
      }
      self.dispatchEvent(msgEvt)
      await clearPromise

      // Case E: notificationclick focuses existing window client and posts PLANIT_NOTIFICATION_CLICK
      let clickPromise = Promise.resolve()
      let clickClosed = false
      const clickEvt = new Event('notificationclick')
      clickEvt.notification = {
        tag: notifId,
        data: {
          version: 1,
          notification_id: notifId,
          recipient_id: recipientId,
          target: `/events/${eventId}`,
        },
        close() {
          clickClosed = true
        },
      }
      clickEvt.waitUntil = p => {
        clickPromise = Promise.resolve(p)
      }
      self.dispatchEvent(clickEvt)
      await clickPromise

      return { shown, closedTags, clickClosed }
    } finally {
      self.registration.showNotification = origShow
      self.registration.getNotifications = origGet
    }
  })

  assert.equal(swBehavior.shown.length, 3)
  // Verify Case A sanitization: HTML stripped, URL stripped, body truncated <= 120 chars, internal target preserved
  const first = swBehavior.shown[0]
  assert.equal(first.title, 'Asado en el parque')
  assert.equal(first.options.body.includes('<script>'), false)
  assert.ok(Array.from(first.options.body).length <= 120)
